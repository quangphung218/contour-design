#!/usr/bin/env python3
"""License files shipped with the app, generated from the repo.

  scripts/licenses.py write    rewrite THIRD-PARTY-LICENSES and the NOTICE
                               "Modified files" section (`make licenses`)
  scripts/licenses.py check    fail when either is out of date (`make check`)

THIRD-PARTY-LICENSES comes from Cargo.lock (`cargo metadata`, every crate a
workspace crate reaches through normal dependencies, all targets) plus the
vendored web assets in VENDORED. Each crate brings the license files of its
published package; a crate that ships none gets the standard text from
scripts/license-texts/. Output depends only on the lock file and the repo.

The NOTICE section lists the files under content/ that differ from OpenDesign
commit UPSTREAM_COMMIT (Apache-2.0 section 4(b)). It needs a checkout of
open-design: $OPEN_DESIGN, default ~/Documents/GitHub/open-design. Without
one, `check` says so and skips that part; `write` fails.

Options: --third-party PATH, --notice PATH (default: the files at the repo root).
"""

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEXTS = ROOT / "scripts" / "license-texts"
UPSTREAM_COMMIT = "e03d5c2"
NOTICE_BEGIN = "Modified files (generated by `make licenses`, do not edit)"
NOTICE_END = "End of modified files"

# Vendored assets that ship in the app: (name, version, license, license files).
VENDORED = [
    ("xterm.js (@xterm/xterm)", "6.0.0", "MIT", ["crates/od-ui/vendor/xterm/LICENSE"]),
    ("@xterm/addon-fit", "0.11.0", "MIT", ["crates/od-ui/vendor/xterm/LICENSE.addon-fit"]),
    ("Remix Icon", "4.8.0", "Apache-2.0", ["crates/od-ui/vendor/remixicon/LICENSE"]),
    ("Geist, Geist Mono", "1.8.2", "OFL-1.1", ["crates/od-ui/vendor/fonts/OFL.txt"]),
    ("react", "18.3.1", "MIT", ["crates/od-preview/vendor/react-runtime/licenses/react.LICENSE"]),
    ("react-dom", "18.3.1", "MIT", ["crates/od-preview/vendor/react-runtime/licenses/react-dom.LICENSE"]),
    ("sucrase", "3.35.0", "MIT", ["crates/od-preview/vendor/react-runtime/licenses/sucrase.LICENSE"]),
    ("lines-and-columns", "1.2.4", "MIT", ["crates/od-preview/vendor/react-runtime/licenses/lines-and-columns.LICENSE"]),
    ("ts-interface-checker", "0.1.13", "Apache-2.0", ["crates/od-preview/vendor/react-runtime/licenses/ts-interface-checker.LICENSE"]),
    ("@jridgewell/gen-mapping", "0.3.13", "MIT", ["crates/od-preview/vendor/react-runtime/licenses/@jridgewell-gen-mapping.LICENSE"]),
    ("@jridgewell/resolve-uri", "3.1.2", "MIT", ["crates/od-preview/vendor/react-runtime/licenses/@jridgewell-resolve-uri.LICENSE"]),
    ("@jridgewell/sourcemap-codec", "1.6.0", "MIT", ["crates/od-preview/vendor/react-runtime/licenses/@jridgewell-sourcemap-codec.LICENSE"]),
    ("@jridgewell/trace-mapping", "0.3.31", "MIT", ["crates/od-preview/vendor/react-runtime/licenses/@jridgewell-trace-mapping.LICENSE"]),
]

# One alternative of an `A OR B` expression is picked, in this order.
PREFERRED = ["MIT", "Apache-2.0", "BSD-3-Clause", "BSD-2-Clause", "ISC", "Zlib", "Unicode-3.0",
             "MPL-2.0", "CC0-1.0", "BSL-1.0", "CDLA-Permissive-2.0", "Apache-2.0 WITH LLVM-exception"]
LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|notice|unlicense)", re.IGNORECASE)
# File name hints for the license an alternative names (LICENSE-MIT, LICENSE.apache2…).
FILE_HINTS = {"MIT": "mit", "Apache-2.0": "apache", "BSD-3-Clause": "bsd", "BSD-2-Clause": "bsd",
              "ISC": "isc", "Zlib": "zlib", "Unicode-3.0": "unicode", "BSL-1.0": "boost",
              "CC0-1.0": "cc0", "MPL-2.0": "mpl"}


def die(msg):
    print(f"licenses: {msg}", file=sys.stderr)
    sys.exit(1)


def read_text(path):
    raw = Path(path).read_bytes().decode("utf-8", errors="replace")
    lines = [line.rstrip() for line in raw.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    return "\n".join(lines).strip("\n") + "\n"


def normalize_expr(expr):
    """`MIT/Apache-2.0` and `Apache-2.0 / MIT` are old spellings of OR."""
    return re.sub(r"\s*/\s*", " OR ", expr or "").strip()


def choose(expr):
    """The alternative of a top-level OR this distribution uses."""
    expr = normalize_expr(expr)
    if " AND " in expr or "(" in expr:
        return expr
    options = [o.strip() for o in expr.split(" OR ")]
    for want in PREFERRED:
        if want in options:
            return want
    return options[0]


def shipped_crates():
    run = subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"],
                         cwd=ROOT, capture_output=True, text=True)
    if run.returncode != 0:
        die(f"cargo metadata failed:\n{run.stderr.strip()}")
    meta = json.loads(run.stdout)
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    workspace = set(meta["workspace_members"])
    seen, stack = set(), list(workspace)
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    crates = [packages[p] for p in seen - workspace]
    return sorted(crates, key=lambda p: (p["name"], version_key(p["version"])))


def version_key(version):
    return [(0, int(x), "") if x.isdigit() else (1, 0, x) for x in re.split(r"[.+-]", version)]


def crate_texts(pkg, chosen):
    """(file label, text) pairs for a crate, or [] when it ships none."""
    crate_dir = Path(pkg["manifest_path"]).parent
    names = sorted(f.name for f in crate_dir.iterdir() if f.is_file() and LICENSE_FILE.match(f.name))
    if pkg.get("license_file"):
        extra = (crate_dir / pkg["license_file"]).resolve()
        if extra.is_file() and extra.parent == crate_dir and extra.name not in names:
            names.append(extra.name)
    notices = [n for n in names if n.lower().startswith("notice")]
    licenses = [n for n in names if n not in notices]
    hint = FILE_HINTS.get(chosen)
    if hint:
        specific = [n for n in licenses if hint in n.lower()]
        # Files named for another license (LICENSE-APACHE when MIT is chosen) are left out.
        if specific:
            licenses = specific
        else:
            other = [h for h in FILE_HINTS.values() if h != hint]
            licenses = [n for n in licenses if not any(h in n.lower() for h in other)] or licenses
    return [(n, read_text(crate_dir / n)) for n in licenses + notices]


def standard_text(expr):
    """Standard texts for every license an expression without files needs."""
    ids = [i for i in re.split(r"[()\s]+|AND|OR", expr) if i and i not in ("AND", "OR")]
    texts = []
    for spdx in ids:
        path = ROOT / "LICENSE" if spdx == "Apache-2.0" else TEXTS / f"{spdx}.txt"
        if not path.is_file():
            die(f"no standard text for {spdx}: add scripts/license-texts/{spdx}.txt")
        texts.append((f"standard {spdx} text", read_text(path)))
    return texts


def third_party():
    crates = shipped_crates()
    blocks = {}  # text digest -> [text, [users]]
    order = []

    def add(user, label, text):
        key = hashlib.sha256(re.sub(r"\s+", " ", text).strip().encode()).hexdigest()
        if key not in blocks:
            blocks[key] = [text, []]
            order.append(key)
        blocks[key][1].append(f"{user} ({label})")

    out = [
        "Third-party licenses for Contour",
        "================================",
        "",
        "Generated by `make licenses` (scripts/licenses.py) from Cargo.lock and the",
        "vendored assets below. Do not edit by hand: `make check` fails when this",
        "file no longer matches the dependencies.",
        "",
        "Contour is licensed under the Apache License 2.0 (LICENSE). It is built on",
        "OpenDesign by nexu-io (Apache-2.0); see NOTICE. Bundled content (skills,",
        "design templates, design systems, craft, prompt templates) keeps its own",
        "LICENSE files under content/.",
        "",
        "",
        "1. Vendored web assets",
        "----------------------",
        "",
    ]
    for name, version, lic, files in VENDORED:
        out.append(f"{name} {version} -- {lic}")
        for f in files:
            if not (ROOT / f).is_file():
                die(f"missing vendored license file {f}")
            add(f"{name} {version}", Path(f).name, read_text(ROOT / f))
    title = f"2. Rust crates ({len(crates)})"
    out += ["", "", title, "-" * len(title), ""]
    mpl = []
    for pkg in crates:
        expr = pkg.get("license") or "(see license file)"
        chosen = choose(expr)
        used = "" if chosen == normalize_expr(expr) else f", used under {chosen}"
        repo = pkg.get("repository") or f"https://crates.io/crates/{pkg['name']}"
        out.append(f"{pkg['name']} {pkg['version']} -- {expr}{used} -- {repo}")
        texts = crate_texts(pkg, chosen)
        user = f"{pkg['name']} {pkg['version']}"
        if not texts:
            authors = ", ".join(pkg.get("authors") or []) or "the authors"
            user = f"{user}, Copyright (c) {authors}"
            texts = standard_text(chosen)
        for label, text in texts:
            add(user, label, text)
        if "MPL-2.0" in chosen:
            mpl.append(pkg)
    out += [
        "", "",
        "3. MPL-2.0 source code",
        "----------------------",
        "",
        "These crates are used unmodified under the Mozilla Public License 2.0. Their",
        "Source Code Form is available from crates.io and from their repositories:",
        "",
    ]
    for pkg in mpl:
        out.append(f"{pkg['name']} {pkg['version']}: https://crates.io/crates/{pkg['name']}/{pkg['version']}"
                   f" ({pkg.get('repository') or 'no repository listed'})")
    out += ["", "", "4. License texts", "----------------", ""]
    for key in order:
        text, users = blocks[key]
        out.append("=" * 80)
        out += [f"Used by: {u}" for u in users]
        out.append("=" * 80)
        out.append("")
        out.append(text.rstrip("\n"))
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def upstream_dir():
    path = Path(os.environ.get("OPEN_DESIGN") or Path.home() / "Documents/GitHub/open-design")
    ok = (path / ".git").exists() and subprocess.run(
        ["git", "-C", str(path), "cat-file", "-e", f"{UPSTREAM_COMMIT}^{{commit}}"],
        capture_output=True).returncode == 0
    return path if ok else None


def modified_files(upstream):
    tree = subprocess.run(["git", "-C", str(upstream), "ls-tree", "-r", UPSTREAM_COMMIT],
                          check=True, capture_output=True, text=True).stdout
    theirs = {}
    for line in tree.splitlines():
        info, path = line.split("\t", 1)
        theirs[path] = info.split()[2]
    ours = subprocess.run(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", "content"],
                          cwd=ROOT, check=True, capture_output=True).stdout.decode().split("\0")
    ours = sorted(p for p in ours if p and (ROOT / p).is_file())
    hashes = subprocess.run(["git", "hash-object", "--stdin-paths"], cwd=ROOT, check=True,
                            input="\n".join(ours) + "\n", capture_output=True, text=True).stdout.split()
    changed = []
    for path, blob in zip(ours, hashes):
        rel = path.removeprefix("content/")
        if rel in theirs and theirs[rel] != blob:
            changed.append(path)
    return changed


def notice_section(changed):
    groups = {}
    for path in changed:
        parts = path.split("/")
        entry = 4 if parts[1] == "plugins" else 2  # content/plugins/_official/<kind>/<entry>/
        key = "/".join(parts[:entry] + ["*"] + parts[entry + 1:]) if len(parts) > entry + 1 else path
        groups.setdefault(key, []).append(path)
    lines = [
        NOTICE_BEGIN,
        f"These {len(changed)} files under content/ were modified by Contour from OpenDesign commit",
        f"{UPSTREAM_COMMIT} (Apache-2.0 section 4(b)); `*` is one entry folder. Files added by Contour",
        "are not listed. `git log -- <path>` shows each change.",
    ]
    for key in sorted(groups):
        paths = groups[key]
        if len(paths) == 1:
            lines.append(f"- {paths[0]}")
        else:
            lines.append(f"- {key} ({len(paths)} files)")
    lines.append(NOTICE_END)
    return "\n".join(lines) + "\n"


def with_section(notice, section):
    start = notice.find(NOTICE_BEGIN)
    if start < 0:
        return notice.rstrip("\n") + "\n\n" + section
    end = notice.find(NOTICE_END, start)
    if end < 0:
        die(f"NOTICE has '{NOTICE_BEGIN}' but no '{NOTICE_END}'")
    end = notice.index("\n", end) + 1 if "\n" in notice[end:] else len(notice)
    return notice[:start] + section + notice[end:]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("mode", choices=["write", "check"])
    parser.add_argument("--third-party", type=Path, default=ROOT / "THIRD-PARTY-LICENSES")
    parser.add_argument("--notice", type=Path, default=ROOT / "NOTICE")
    args = parser.parse_args()

    expected = third_party()
    upstream = upstream_dir()
    notice = args.notice.read_text() if args.notice.is_file() else ""
    if upstream is None:
        if args.mode == "write":
            die(f"no open-design checkout with {UPSTREAM_COMMIT}: set OPEN_DESIGN")
        print(f"licenses: no open-design checkout with {UPSTREAM_COMMIT} (set OPEN_DESIGN); "
              "NOTICE modified files not checked")
        new_notice = notice
    else:
        new_notice = with_section(notice, notice_section(modified_files(upstream)))

    if args.mode == "write":
        args.third_party.write_text(expected)
        args.notice.write_text(new_notice)
        return
    stale = []
    if not args.third_party.is_file() or args.third_party.read_text() != expected:
        stale.append(str(args.third_party.relative_to(ROOT) if args.third_party.is_relative_to(ROOT) else args.third_party))
    if new_notice != notice:
        stale.append(f"{args.notice.name} (modified files)")
    if stale:
        die(f"out of date: {', '.join(stale)}. Run `make licenses` and commit the result.")
    print("licenses: THIRD-PARTY-LICENSES and NOTICE are up to date")


if __name__ == "__main__":
    main()
